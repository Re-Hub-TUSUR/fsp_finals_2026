package ru.sportikus.moderation;

/** Результат автопроверки мероприятия. */
public enum ModerationStatus {
    /** Фильтр ничего не нашёл — опубликовано сразу. */
    CLEAN,
    /** Идёт проверка ИИ; мероприятие скрыто. */
    PENDING,
    /** Было сомнительным, ИИ пропустил (или был недоступен): администратору стоит присмотреться. */
    FLAGGED,
    /** ИИ отклонил: мероприятие снято с публикации с причиной. */
    REJECTED,
    /** Администратор проверил вручную. */
    REVIEWED
}
